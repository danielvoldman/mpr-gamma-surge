"""MS15a (sub-step 18, DL-736 C4 (h)): write docs/figure_map.md (plan section 10.1 lists it).

  .venv/Scripts/python.exe scripts/ms15a_write_figure_map.py [--check]

Reads docs/ms13_journal_final_hashes.txt (the 13 journal figures and the eleven drafts, full SHA-256), docs/ms13_figure_manifest.csv (the draft files)
and, when present, the git-ignored provenance records figures/journal/<ID>/<ID>_journal_provenance.json (only to name the result families under
results/ that each figure reads; the paths are copied, nothing is computed). No hash is typed or computed: every hash is copied from the hash list or
the manifest. Writes only docs/figure_map.md (LF, UTF-8). --check writes nothing and exits 1 if the file on disk differs from what would be written.
"""
import argparse
import csv
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HASHES = ROOT / "docs" / "ms13_journal_final_hashes.txt"
MANIFEST = ROOT / "docs" / "ms13_figure_manifest.csv"
OUT = ROOT / "docs" / "figure_map.md"

SECTION = re.compile(r"^## (\S+) \(journal main version; draft audit copy: (\S+)\)\s*$")
LINE = re.compile(r"^([0-9a-f]{64})  (.+?)\s{2,}(\S+)\s*$")


def parse_hash_list(text: str):
    """-> (order, info) where info[ID] = {'draft': ID, 'commit', 'digest', 'files': [(kind, path, sha)]}; drafts = [(figure, path, sha)]."""
    info, order, drafts, cur, in_drafts = {}, [], [], None, False
    for ln in text.splitlines():
        m = SECTION.match(ln)
        if m:
            cur, in_drafts = m.group(1), False
            order.append(cur)
            info[cur] = {"draft": m.group(2), "commit": None, "digest": None, "files": []}
            continue
        if ln.startswith("## The eleven draft files"):
            cur, in_drafts = None, True
            continue
        if cur and ln.startswith("built from commit: "):
            info[cur]["commit"] = ln.split(": ", 1)[1].strip()
        elif cur and ln.startswith("drawn-data digest: "):
            info[cur]["digest"] = ln.split(": ", 1)[1].strip()
        else:
            m = LINE.match(ln)
            if m and cur:
                info[cur]["files"].append((m.group(2).strip(), m.group(3), m.group(1)))
            elif m and in_drafts:
                drafts.append((m.group(2).strip(), m.group(3), m.group(1)))
    return order, info, drafts


def families(fig_id: str):
    """Result families (first folder under results/) of the inputs recorded in the local provenance record; None if the record is not present."""
    p = ROOT / "figures" / "journal" / fig_id / f"{fig_id}_journal_provenance.json"
    if not p.is_file():
        return None
    prov = json.loads(p.read_text(encoding="utf-8"))
    fams = set()
    for rec in [*prov.get("inputs", []), *prov.get("input_tables", [])]:
        parts = rec["path"].replace("\\", "/").split("/")
        if parts[0] == "results" and len(parts) > 2:
            fams.add(parts[1])
    return sorted(fams)


def build() -> str:
    order, info, drafts = parse_hash_list(HASHES.read_text(encoding="utf-8"))
    with MANIFEST.open(encoding="utf-8", newline="") as f:
        man = list(csv.DictReader(f))
    man_by_path = {r["file"]: r["sha256"] for r in man}
    for fig, path, sha in drafts:                         # the hash list and the manifest agree on every draft file
        if man_by_path.get(path) != sha:
            raise SystemExit(f"draft file {path}: hash list and manifest disagree")
    out = ["# Figure map (generated by scripts/ms15a_write_figure_map.py; do not edit by hand)", "",
           "Written for: readers of the release who want to know which file is which figure. Every hash is copied by script from docs/ms13_journal_final_hashes.txt "
           "(journal figures and drafts) and checked against docs/ms13_figure_manifest.csv (drafts); none is typed or recomputed here. The figure files themselves are "
           "git-ignored (figures/) and are not in any tagged tree; their SHA-256 hashes are here, in docs/ms13_journal_final_hashes.txt and in the tag messages.", "",
           "The journal files are the MAIN versions; the draft files (figures/<ID>/) are audit copies. F5 and F5c are two journal files of the draft F5; F4a and F4b are two "
           "journal files of the draft F4 (a departure from the plan's single figures, rulings T1 and K2 in docs/ms13_figure_rules.md). FS6 is not produced "
           "(user ruling of 2026-11-09, docs/ms13_close.md). The 'result families' column lists the folders under results/ read by the figure, from the git-ignored "
           "provenance record figures/journal/<ID>/<ID>_journal_provenance.json (empty if that record is not on this machine). Tags: fig-<ID>-v1 exists for every journal figure "
           "and describes the v1 files (superseded); fig-<ID>-v2 is planned for the files listed here and is not created (see README.md).", "",
           "## 1. The 13 journal figures", "",
           "| Journal figure (short name) | Draft counterpart | Main files | Result families read | Build commit | Tag |",
           "| --- | --- | --- | --- | --- | --- |"]
    for fid in order:
        d = info[fid]
        main = [p for k, p, _ in d["files"] if k in ("png", "tiff")]
        fams = families(fid)
        fam_txt = ", ".join(fams) if fams else "(provenance record not on this machine)"
        out.append(f"| {fid} | {d['draft']} | {'<br>'.join('`' + p + '`' for p in main)} | {fam_txt} | `{d['commit']}` | fig-{fid}-v1 (v2 planned: fig-{fid}-v2, not created) |")
    out += ["", "## 2. Journal files with full SHA-256", "",
            "| Figure | Kind | Path | SHA-256 |", "| --- | --- | --- | --- |"]
    for fid in order:
        for kind, path, sha in info[fid]["files"]:
            out.append(f"| {fid} | {kind} | `{path}` | `{sha}` |")
    out += ["", "## 3. Drawn-data digests", "", "| Figure | Drawn-data digest (SHA-256) |", "| --- | --- |"]
    for fid in order:
        out.append(f"| {fid} | `{info[fid]['digest']}` |")
    out += ["", "## 4. The eleven draft figures (audit copies) with full SHA-256", "",
            "| Draft figure | Path | SHA-256 |", "| --- | --- | --- |"]
    for fig, path, sha in drafts:
        out.append(f"| {fig} | `{path}` | `{sha}` |")
    out.append("")
    return "\n".join(out)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    text = build()
    if a.check:
        same = OUT.is_file() and OUT.read_bytes() == text.encode("utf-8")
        print("docs/figure_map.md equals the generated text" if same else "docs/figure_map.md differs from the generated text")
        return 0 if same else 1
    OUT.write_bytes(text.encode("utf-8"))
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text.encode('utf-8'))} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
